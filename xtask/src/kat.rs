//! `cargo xtask kat`: regenerates known-answer vectors from independent
//! implementations, recording where each one came from.
//!
//! - KDF vectors come from OpenSSL's KBKDF configured exactly as RFC 9946
//!   Appendix A configures it, so they check our hand-written KDF against an
//!   implementation that shares none of its code.
//! - HMAC-SHA-256 vectors are extracted from the text of RFC 4231, which must
//!   be downloaded to `reference/standards/rfc4231.txt` first.

use std::fmt::Write as _;
use std::process::Command;

/// Shared Keys (hex) and authUnixTime values to generate vectors for.
const KDF_CASES: &[(&str, &[u32])] = &[
    // "UDPSTP-example-key", the text key used in the research note.
    (
        "5544505354502d6578616d706c652d6b6579",
        &[0, 1, 1_758_480_000, 4_294_967_295],
    ),
    // A key with zero bytes inside it ("Key\0\0key"): must not be truncated.
    ("4b657900006b6579", &[1_758_480_000]),
    // A key starting with a zero byte.
    ("00ff00ff00ff00ff", &[1_758_480_000]),
    // A 100-octet key (0x00, 0x01, ...), longer than the SHA-256 block, so
    // HMAC hashes it first.
    (LONG_KEY, &[1_758_480_000]),
];

const LONG_KEY: &str = "000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f\
                        202122232425262728292a2b2c2d2e2f303132333435363738393a3b3c3d3e3f\
                        404142434445464748494a4b4c4d4e4f505152535455565758595a5b5c5d5e5f\
                        60616263";

const VECTOR_DIR: &str = "src/tests/wire/vectors";

pub fn run() -> Result<(), String> {
    write_vectors("kdf-openssl.txt", &kdf_vectors()?)?;
    write_vectors("hmac-rfc4231.txt", &hmac_rfc4231_vectors()?)?;
    Ok(())
}

fn write_vectors(name: &str, contents: &str) -> Result<(), String> {
    let path = crate::workspace_root().join(VECTOR_DIR).join(name);
    std::fs::write(&path, contents).map_err(|e| format!("writing {}: {e}", path.display()))?;
    println!("wrote {}", path.display());
    Ok(())
}

fn kdf_vectors() -> Result<String, String> {
    let version = openssl(&["version"])?;
    let mut out = String::new();
    let _ = writeln!(
        out,
        "# KDF known-answer vectors for RFC 9946 §5.4.1 and Appendix A.\n\
         # Generated by `cargo xtask kat`; do not edit by hand.\n\
         # Source: {version}\n\
         # Command per vector:\n\
         #   openssl {}\n\
         # Format: <Shared Key hex> <authUnixTime> <64-octet output hex>\n\
         # The first 32 octets are the Client Authentication Key, the last 32\n\
         # the Server Authentication Key.",
        kdf_args("<Shared Key hex>", "<authUnixTime>").join(" ")
    );
    for (key, times) in KDF_CASES {
        let key: String = key.chars().filter(char::is_ascii_hexdigit).collect();
        for time in *times {
            let output = openssl_kdf(&key, *time)?;
            let _ = writeln!(out, "{key} {time} {output}");
        }
    }
    Ok(out)
}

/// OpenSSL's KBKDF with the settings of RFC 9946 Appendix A: counter mode,
/// HMAC-SHA-256, label "UDPSTP" (passed as OpenSSL's salt), context = the
/// decimal authUnixTime (passed as info), L and separator enabled, r = 32.
fn kdf_args(key_hex: &str, time: &str) -> Vec<String> {
    [
        "kdf",
        "-keylen",
        "64",
        "-kdfopt",
        "mode:COUNTER",
        "-kdfopt",
        "mac:HMAC",
        "-kdfopt",
        "digest:SHA256",
        "-kdfopt",
        &format!("hexkey:{key_hex}"),
        "-kdfopt",
        "salt:UDPSTP",
        "-kdfopt",
        &format!("info:{time}"),
        "-kdfopt",
        "use-l:1",
        "-kdfopt",
        "use-separator:1",
        "-kdfopt",
        "r:32",
        "KBKDF",
    ]
    .iter()
    .map(|s| s.to_string())
    .collect()
}

fn openssl_kdf(key_hex: &str, time: u32) -> Result<String, String> {
    let args = kdf_args(key_hex, &time.to_string());
    let output = openssl(&args.iter().map(String::as_str).collect::<Vec<_>>())?;
    // OpenSSL prints the key as colon-separated hex octets.
    let hex: String = output
        .chars()
        .filter(char::is_ascii_hexdigit)
        .collect::<String>()
        .to_ascii_lowercase();
    if hex.len() != 128 {
        return Err(format!("unexpected openssl kdf output: {output}"));
    }
    Ok(hex)
}

fn openssl(args: &[&str]) -> Result<String, String> {
    let output = Command::new("openssl")
        .args(args)
        .output()
        .map_err(|e| format!("running openssl (is it on PATH?): {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "openssl {} failed: {}",
            args.join(" "),
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    Ok(String::from_utf8_lossy(&output.stdout).trim().to_string())
}

/// Extracts the HMAC-SHA-256 test cases of RFC 4231 §4.2-§4.8.
fn hmac_rfc4231_vectors() -> Result<String, String> {
    let source = crate::workspace_root().join("reference/standards/rfc4231.txt");
    let text = std::fs::read_to_string(&source).map_err(|e| {
        format!(
            "reading {}: {e}\ndownload https://www.rfc-editor.org/rfc/rfc4231.txt there first",
            source.display()
        )
    })?;
    let mut out = String::from(
        "# HMAC-SHA-256 known-answer vectors: RFC 4231 §4.2-§4.8, test cases 1-7.\n\
         # Extracted from https://www.rfc-editor.org/rfc/rfc4231.txt by `cargo xtask kat`;\n\
         # do not edit by hand.\n\
         # Format: <test case> <key hex> <data hex> <HMAC-SHA-256 hex>\n\
         # Case 5's output is truncated to 128 bits by the RFC, so it is 16 octets.\n",
    );
    for case in parse_rfc4231(&text)? {
        let _ = writeln!(
            out,
            "{} {} {} {}",
            case.number, case.key, case.data, case.mac
        );
    }
    Ok(out)
}

#[derive(Debug, Default)]
struct Rfc4231Case {
    number: u32,
    key: String,
    data: String,
    mac: String,
}

impl Rfc4231Case {
    fn field(&mut self, index: usize) -> &mut String {
        match index {
            0 => &mut self.key,
            1 => &mut self.data,
            _ => &mut self.mac,
        }
    }
}

/// Reads each test case's Key, Data and HMAC-SHA-256 fields. A field is a
/// label followed by hex (the RFC omits the `=` after `Key` in case 3) and
/// continues on following lines indented to the value column.
fn parse_rfc4231(text: &str) -> Result<Vec<Rfc4231Case>, String> {
    const LABELS: [&str; 3] = ["Key", "Data", "HMAC-SHA-256"];
    let start = text
        .rfind("4.2.  Test Case 1")
        .ok_or("RFC 4231 test cases not found")?;
    let end = text
        .rfind("5.  Security Considerations")
        .ok_or("RFC 4231 section 5 not found")?;
    let mut cases: Vec<Rfc4231Case> = Vec::new();
    let mut current: Option<usize> = None;
    for line in text[start..end].lines() {
        if let Some((_, number)) = line
            .strip_prefix("4.")
            .and_then(|rest| rest.split_once("Test Case "))
        {
            let number = number
                .trim()
                .parse()
                .map_err(|_| format!("bad test case line: {line}"))?;
            cases.push(Rfc4231Case {
                number,
                ..Default::default()
            });
            current = None;
            continue;
        }
        let Some(case) = cases.last_mut() else {
            continue;
        };
        let trimmed = line.trim_start();
        let label = LABELS
            .iter()
            .position(|l| trimmed.starts_with(l) && trimmed[l.len()..].starts_with(' '));
        if let Some(index) = label {
            let value = trimmed[LABELS[index].len()..].trim_start();
            let value = value.strip_prefix('=').unwrap_or(value).trim_start();
            case.field(index).push_str(leading_hex(value));
            current = Some(index);
        } else if trimmed.starts_with("HMAC-SHA-") {
            current = None;
        } else if let Some(index) = current {
            let indent = line.len() - trimmed.len();
            let hex = leading_hex(trimmed);
            if indent >= 10 && !hex.is_empty() {
                case.field(index).push_str(hex);
            }
        }
    }
    let complete = cases
        .iter()
        .all(|c| !c.key.is_empty() && !c.data.is_empty() && !c.mac.is_empty());
    if cases.len() != 7 || !complete {
        return Err(format!(
            "expected 7 complete RFC 4231 test cases, got {cases:?}"
        ));
    }
    Ok(cases)
}

fn leading_hex(s: &str) -> &str {
    let end = s.find(|c: char| !c.is_ascii_hexdigit()).unwrap_or(s.len());
    &s[..end]
}
